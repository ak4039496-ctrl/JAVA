// Program: Convert number to string using valueOf()

public class string_valueOf {
    public static void main(String[] args) {
        // Declare an integer
        int num = 123;

        //Convert to string
        String str = String.valueOf(num);

        //  Print result
        System.out.println("String value => " + str);
    }
}
