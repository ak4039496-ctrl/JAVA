// Program: Repeat string multiple times

public class string_repeat {
    public static void main(String[] args) {
        //  Declare string
        String text = "Hi ";

        //  Repeat 3 times
        String result = text.repeat(3);

        // Print result
        System.out.println("Repeated => " + result);
    }
}
