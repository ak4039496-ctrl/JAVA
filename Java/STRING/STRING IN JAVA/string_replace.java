// Program: Replace characters in string

public class string_replace {
    public static void main(String[] args) {
        // Declare a string
        String text = "banana";

        //  Replace 'a' with 'o'
        String replaced = text.replace('a', 'o');

        // Print result
        System.out.println("Replaced string => " + replaced);
    }
}
