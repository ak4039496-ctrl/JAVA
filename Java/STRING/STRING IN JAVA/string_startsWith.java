// Program: Check if string starts with given prefix

public class string_startsWith {
    public static void main(String[] args) {
        // Declare a string
        String text = "Hello World";

        //Check if starts with "Hello"
        boolean result = text.startsWith("Hello");

        // Print result
        System.out.println("Starts with Hello? " + result);
    }
}
