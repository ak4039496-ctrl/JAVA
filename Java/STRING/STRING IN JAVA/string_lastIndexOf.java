// Program: Find last index of character

public class string_lastIndexOf {
    public static void main(String[] args) {
        //  Declare a string
        String text = "banana";

        // Find last index of 'a'
        int index = text.lastIndexOf('a');

        // Print result
        System.out.println("Last Index => " + index);
    }
}
