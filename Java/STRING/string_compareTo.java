// Program: Compare two strings using compareTo()

public class string_compareTo {
    public static void main(String[] args) {
        // Declare two strings
        String s1 = "Apple";
        String s2 = "Banana";

        // Compare using compareTo()
        int result = s1.compareTo(s2); // Case-sensitive

        //  Print result
        System.out.println("Comparison result = " + result);
    }
}
