// Program: Check if string ends with given suffix

public class string_endsWith {
    public static void main(String[] args) {
        // Step 1: Declare a string
        String text = "Hello World";

        // Step 2: Check if ends with "World"
        boolean result = text.endsWith("World");

        // Step 3: Print result
        System.out.println("Ends with World? " + result);
    }
}
