// Program: Find character at position

public class string_charAt {
    public static void main(String[] args) {
        //  Declare a string
        String text = "Hello";

        //  Get character at index 1
        char ch = text.charAt(1);

        // Print result
        System.out.println("Character => " + ch);
    }
}
