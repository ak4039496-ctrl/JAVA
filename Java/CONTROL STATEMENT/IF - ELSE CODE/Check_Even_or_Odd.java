public class Check_Even_or_Odd {
    public static void main(String[] args) {
        int num = 7; // Example number

        // if-else to check even or odd
        if(num % 2 == 0) {
            System.out.println(num + " is Even");
        } else {
            System.out.println(num + " is Odd");
        }
    }
}
