// Program: Print numbers 1 to 10 using while loop

public class print_1_to_10 {
    public static void main(String[] args) {
        int i = 1; // initialize counter with 1

        // loop until i <= 10
        while (i <= 10) {
            System.out.println(i); // print current value of i
            i++; // increase i by 1
        }
    }
}
