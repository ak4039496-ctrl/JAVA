// Program: Print odd numbers from 1 to 50 

public class print_odd_1_to_50 {
    public static void main(String[] args) {
        int i = 1; // start with first odd number

        while (i <= 50) {
            System.out.println(i); // print current odd number
            i += 2; // move to next odd number
        }
    }
}
