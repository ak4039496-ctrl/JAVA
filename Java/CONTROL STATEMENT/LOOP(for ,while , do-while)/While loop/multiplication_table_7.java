// Program: Print multiplication table of 7 

public class multiplication_table_7 {
    public static void main(String[] args) {
        int i = 1; // start with 1

        while (i <= 10) {
            System.out.println("7 x " + i + " = " + (7 * i));
            i++; // move to next multiplier
        }
    }
}
