// Program: Print natural numbers in reverse order

public class print_reverse_natural_numbers {
    public static void main(String[] args) {
        int i = 15; // start with 

        // loop until i >= 1
        while (i >= 1) {
            System.out.println(i); // print current number
            i--; // move backward
        }
    }
}
