// Program: Print even numbers from 1 to 50 using while loop

public class print_even_1_to_50 {
    public static void main(String[] args) {
        int i = 2; // start with first even number

        while (i <= 50) {
            System.out.println(i); // print current even number
            i += 2; // move to next even number
        }
    }
}
