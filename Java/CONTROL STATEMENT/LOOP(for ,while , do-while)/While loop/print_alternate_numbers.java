// Program: Print alternate numbers from 1 to 20 

public class print_alternate_numbers {
    public static void main(String[] args) {
        int i = 1; // start with 1

        while (i <= 20) {
            System.out.println(i); // print current number
            i += 2; // skip one number
        }
    }
}
