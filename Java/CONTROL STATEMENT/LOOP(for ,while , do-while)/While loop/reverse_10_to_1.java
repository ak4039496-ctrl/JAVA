// Program: Print numbers from 10 to 1

public class reverse_10_to_1 {
    public static void main(String[] args) {
        int i = 10; // start from 10

        // loop until i >= 1
        while (i >= 1) {
            System.out.println(i); // print current number
            i--; // decrease i by 1
        }
    }
}
