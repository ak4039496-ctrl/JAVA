// Program: Print alphabets A to Z 

public class print_alphabets_A_to_Z {
    public static void main(String[] args) {
        char ch = 'A'; // start with A

        while (ch <= 'Z') {
            System.out.println(ch); // print current alphabet
            ch++; // move to next alphabet
        }
    }
}
