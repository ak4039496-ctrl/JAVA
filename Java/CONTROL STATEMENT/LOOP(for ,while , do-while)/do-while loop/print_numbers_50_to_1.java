// Program: Print numbers from 50 to 1

public class print_numbers_50_to_1 {
    public static void main(String[] args) {
        int i = 50; // Step 1: Initialize
        do {
            System.out.print(i + " "); // Step 2: Print number
            i--; // Step 3: Decrement
        } while (i >= 1); // Step 4: Condition check
    }
}
