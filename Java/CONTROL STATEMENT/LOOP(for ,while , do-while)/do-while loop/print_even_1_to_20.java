// Program: Print even numbers from 1 to 20

public class print_even_1_to_20 {
    public static void main(String[] args) {
        int i = 2; //  Start from first even number
        do {
            System.out.println(i); // Print even number
            i += 2; //  Increment by 2
        } while (i <= 20); // Condition check
    }
}
