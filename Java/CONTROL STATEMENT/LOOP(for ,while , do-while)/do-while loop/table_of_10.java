// Program: Print multiplication table of 10

public class table_of_10 {
    public static void main(String[] args) {
        int i = 1; // Step 1: Initialize
        do {
            System.out.println("10 x " + i + " = " + (10 * i)); // Step 2: Print
            i++; // Step 3: Increment
        } while (i <= 10); // Step 4: Condition check
    }
}
