// Program: Print odd numbers from 1 to 20

public class print_odd_1_to_20 {
    public static void main(String[] args) {
        int i = 1; // Start from first odd number
        do {
            System.out.println(i); // Print odd number
            i += 2; //  Increment by 2
        } while (i <= 20); // Condition check
    }
}
