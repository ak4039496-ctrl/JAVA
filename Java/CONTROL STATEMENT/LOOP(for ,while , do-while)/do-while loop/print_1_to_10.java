// Program: Print numbers from 1 to 10 using do-while loop

public class print_1_to_10 {
    public static void main(String[] args) {
        int i = 1; // Step 1: Initialize variable
        do {
            System.out.println(i); // Step 2: Print current value
            i++; // Step 3: Increment i
        } while (i <= 10); // Step 4: Condition check
    }
}
