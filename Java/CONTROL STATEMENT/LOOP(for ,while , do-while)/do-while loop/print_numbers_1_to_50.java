// Program: Print numbers from 1 to 50

public class print_numbers_1_to_50 {
    public static void main(String[] args) {
        int i = 1; // Step 1: Initialize
        do {
            System.out.print(i + " "); // Step 2: Print number
            i++; // Step 3: Increment
        } while (i <= 50); // Step 4: Condition check
    }
}
