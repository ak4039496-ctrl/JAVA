// Program: Print numbers from 10 to 1 using do-while loop

public class print_10_to_1 {
    public static void main(String[] args) {
        int i = 10; //  Start from 10
        do {
            System.out.println(i); //  Print current value
            i--; //  Decrement i
        } while (i >= 1); // Condition check
    }
}
