public class menu_driven_program {
    public static void main(String[] args) {
        
        int choice = 2; 
        
        switch(choice) {
            case 1: System.out.println("Hello"); break;
            case 2: System.out.println("Welcome"); break;
            case 3: System.out.println("Goodbye"); break;
            default: System.out.println("Invalid choice!");
        }
    }
}
