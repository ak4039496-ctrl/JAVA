public class holiday_type {
    public static void main(String[] args) {
        
        int choice = 1;
        
        switch(choice) {
            case 1: System.out.println("National Holiday"); break;
            case 2: System.out.println("Festival Holiday"); break;
            case 3: System.out.println("Weekend Holiday"); break;
            default: System.out.println("Invalid holiday!");
        }
    }
}
