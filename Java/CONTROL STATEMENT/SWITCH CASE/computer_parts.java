public class computer_parts {
    public static void main(String[] args) {
        
        int choice = 3;
        
        switch(choice) {
            case 1: System.out.println("CPU"); break;
            case 2: System.out.println("Monitor"); break;
            case 3: System.out.println("Keyboard"); break;
            case 4: System.out.println("Mouse"); break;
            default: System.out.println("Invalid choice!");
        }
    }
}
