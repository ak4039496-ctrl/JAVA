public class animal_sound {
    public static void main(String[] args) {
        
        int choice = 1;
        
        switch(choice) {
            case 1: System.out.println("Dog: Bark"); break;
            case 2: System.out.println("Cat: Meow"); break;
            case 3: System.out.println("Cow: Moo"); break;
            case 4: System.out.println("Lion: Roar"); break;
            default: System.out.println("Unknown animal!");
        }
    }
}
