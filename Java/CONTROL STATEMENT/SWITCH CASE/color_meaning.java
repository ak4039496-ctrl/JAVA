public class color_meaning {
    public static void main(String[] args) {
        
        String color = "Blue";
        
        switch(color) {
            case "Red": System.out.println("Represents Energy"); break;
            case "Green": System.out.println("Represents Nature"); break;
            case "Blue": System.out.println("Represents Calmness"); break;
            case "Yellow": System.out.println("Represents Happiness"); break;
            default: System.out.println("Unknown color!");
        }
    }
}
