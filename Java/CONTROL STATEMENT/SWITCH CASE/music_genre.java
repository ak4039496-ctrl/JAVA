public class music_genre {
    public static void main(String[] args) {
        
        int choice = 4;
        
        switch(choice) {
            case 1: System.out.println("Classical"); break;
            case 2: System.out.println("Rock"); break;
            case 3: System.out.println("Pop"); break;
            case 4: System.out.println("Jazz"); break;
            default: System.out.println("Invalid genre!");
        }
    }
}
