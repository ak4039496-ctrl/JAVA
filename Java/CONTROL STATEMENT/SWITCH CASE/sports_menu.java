public class sports_menu {
    public static void main(String[] args) {
        
        int choice = 4;
        
        switch(choice) {
            case 1: System.out.println("Cricket"); break;
            case 2: System.out.println("Football"); break;
            case 3: System.out.println("Hockey"); break;
            case 4: System.out.println("Badminton"); break;
            default: System.out.println("Invalid choice!");
        }
    }
}
