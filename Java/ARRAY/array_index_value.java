// Program: Print index and value of array

public class array_index_value {
    public static void main(String[] args) {
        int[] arr = {10, 20, 30, 40};
        for(int i = 0; i < arr.length; i++) {
            System.out.println("Index " + i + " => " + arr[i]);
        }
    }
}
