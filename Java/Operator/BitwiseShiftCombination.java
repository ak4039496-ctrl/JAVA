public class BitwiseShiftCombination {
    public static void main(String[] args) {
        int a = 8; // binary 1000
        System.out.println("Left Shift (a<<2) = " + (a << 2));
        System.out.println("Right Shift (a>>1) = " + (a >> 1));
    }
}
