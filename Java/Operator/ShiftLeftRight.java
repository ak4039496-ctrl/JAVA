public class ShiftLeftRight {
    public static void main(String[] args) {
        int a = 16; // binary 10000
        System.out.println("Left Shift (a<<2) => " + (a << 2));
        System.out.println("Right Shift (a>>2) => " + (a >> 2));
    }
}
