public class BitwiseCombination {
    public static void main(String[] args) {
        int a = 6, b = 4;
        System.out.println("a & b => " + (a & b));
        System.out.println("a | b => " + (a | b));
        System.out.println("a ^ b => " + (a ^ b));
    }
}
